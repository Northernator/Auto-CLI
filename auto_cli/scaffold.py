def _module_name(name: str) -> str:
    m = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    if not m or m[0].isdigit():
        m = "app_" + m
    return m


def _py_repr(value) -> str:
    return repr(value)


def _first(bundle: EvidenceBundle, kind: str) -> str | None:
    items = bundle.of_kind(kind)
    return items[0].value if items else None


def generate(
    plan: HarnessPlan,
    bundle: EvidenceBundle,
    out_dir: str | Path,
    name: str | None = None,
    display_name: str | None = None,
    author: str = "auto-cli",
    repl_skin: str | Path | None = None,
    target_root: str | Path | None = None,
) -> Path:
    name = name or re.sub(r"[^a-z0-9]+", "-", Path(plan.target).name.lower()).strip("-")
    display_name = display_name or Path(plan.target).name
    module = _module_name(name)

    dbs = [f.value for f in bundle.of_kind("database")]
    default_db = dbs[0] if dbs else ""
    endpoints = []
    for f in bundle.of_kind("endpoint"):
        v = f.value
        if v.startswith(("http://", "https://")):
            endpoints.append(v)
        elif "127.0.0.1" in v or "localhost" in v:
            endpoints.append("http://" + v.lstrip("/"))
    channels = [f.value for f in bundle.of_kind("ipc_channel")]

    from urllib.parse import urlsplit

    ports: list[int] = []
    origins: list[str] = []
    for u in endpoints:
        try:
            p = urlsplit(u).port
            if p and p not in ports:
                ports.append(p)
            netloc = urlsplit(u).netloc
            if netloc and netloc not in origins:
                origins.append(netloc)
        except ValueError:
            pass

    root = Path(out_dir) / name / "agent-harness"
    pkg = root / "cli_anything" / module
    for d in (pkg / "core", pkg / "skills", pkg / "tests", pkg / "utils"):
        d.mkdir(parents=True, exist_ok=True)

    evidence_block = "\n".join(f"- {e}" for e in plan.evidence) or "- (none recorded)"
    risks_block = "\n".join(f"- {r}" for r in plan.risks) or "- none identified"
    todos_block = "\n".join(f"1. {t}" for t in plan.human_todos) or "1. none"
    agent_rules = "\n".join(
        f"- {c.name}: {c.purpose}" + (" (mutating - always backup first)" if c.mutating else "")
        for c in plan.commands
    )
    commands_block = "\n".join(
        f"# {c.purpose}\ncli-anything-{name} {c.name}"
        for c in plan.commands
    )
    backup_note = (
        "**Backup before any write is mandatory** - this app owns a local database."
        if plan.backup_required
        else "No local database detected during recon."
    )

    (root / f"{name.upper()}.md").write_text(
        SOP_MD.substitute(
            display_name=display_name,
            target=plan.target,
            flavor=plan.primary_flavor,
            flavors=", ".join(plan.flavors),
            evidence_block=evidence_block,
            risks_block=risks_block,
            human_todos=todos_block,
        ),
        encoding="utf-8",
    )

    (root / "setup.py").write_text(
        SETUP_PY.substitute(
            name=name,
            module=module,
            author=author,
            description=f"{display_name} harness ({plan.primary_flavor}) - generated by auto-cli",
        ),
        encoding="utf-8",
    )

    (pkg / "__init__.py").write_text(PKG_INIT.substitute(display_name=display_name), encoding="utf-8")
    (pkg / "__main__.py").write_text(MAIN_PY.substitute(module=module), encoding="utf-8")
    (pkg / "README.md").write_text(
        README_MD.substitute(
            name=name,
            module=module,
            display_name=display_name,
            flavor=plan.primary_flavor,
            backup_note=backup_note,
            human_todos=todos_block,
        ),
        encoding="utf-8",
    )

    (pkg / f"{module}_cli.py").write_text(
        CLI_PY.substitute(name=name, module=module, display_name=display_name),
        encoding="utf-8",
    )

    (pkg / "core" / "__init__.py").write_text(INIT_PY, encoding="utf-8")
    (pkg / "core" / "backend.py").write_text(
        BACKEND_PY.substitute(
            display_name=display_name,
            target_root_repr=_py_repr(
                str(Path(target_root).resolve()) if target_root else str(Path(plan.target).resolve())
            ),
            default_db_repr=_py_repr(default_db),
            ports_repr=_py_repr(ports),
            endpoints_repr=_py_repr(endpoints),
            channels_repr=_py_repr(channels),
            origins_repr=_py_repr(origins),
        ),
        encoding="utf-8",
    )

    (pkg / "skills" / "SKILL.md").write_text(
        SKILL_MD.substitute(
            name=name,
            module=module,
            display_name=display_name,
            flavor=plan.primary_flavor,
            commands_block=commands_block,
            agent_rules=agent_rules,
            evidence_block=evidence_block,
        ),
        encoding="utf-8",
    )

    (pkg / "tests" / "__init__.py").write_text(INIT_PY, encoding="utf-8")
    (pkg / "tests" / "test_core.py").write_text(
        TEST_CORE_PY.substitute(module=module), encoding="utf-8"
    )

    (pkg / "utils" / "__init__.py").write_text(INIT_PY, encoding="utf-8")
    if repl_skin and Path(repl_skin).exists():
        shutil.copyfile(repl_skin, pkg / "utils" / "repl_skin.py")
    else:
        (pkg / "utils" / "repl_skin.py").write_text(REPL_SKIN_PLACEHOLDER, encoding="utf-8")

    report = _forge_report(plan, bundle, name, display_name, module)
    (root / "FORGE-REPORT.md").write_text(report, encoding="utf-8")

    registry_entry = {
        "name": name,
        "display_name": display_name,
        "version": "0.1.0",
        "description": f"{display_name} harness ({plan.primary_flavor}) - scaffolded by auto-cli from REA evidence",
        "requires": None,
        "homepage": "",
        "source_url": None,
        "install_cmd": f"pip install git+https://github.com/HKUDS/CLI-Anything.git#subdirectory={name}/agent-harness",
        "entry_point": f"cli-anything-{name}",
        "skill_md": f"skills/cli-anything-{name}/SKILL.md",
        "category": _category(plan),
        "contributors": [{"name": author, "url": ""}],
    }
    (root / "registry-entry.json").write_text(json.dumps(registry_entry, indent=2), encoding="utf-8")

    return root


def _category(plan: HarnessPlan) -> str:
    return {
        "local-server": "automation",
        "database": "media",
        "mcp-face": "automation",
        "scripting-runtime": "creative",
    }.get(plan.primary_flavor, "uncategorized")


def _forge_report(
    plan: HarnessPlan, bundle: EvidenceBundle, name: str, display_name: str, module: str
) -> str:
    lines = [
        f"# Forge report: {display_name}",
        "",
        "Generated by auto-cli. This document is the audit trail between",
        "REA evidence and the generated harness. Read it before opening a PR.",
        "",
        "## Target",
        "",
        f"`{plan.target}`",
        "",
        "## REA probes",
        "",
        "| command | args | ok | duration |",
        "| --- | --- | --- | --- |",
    ]
    for p in bundle.probes:
        args = " ".join(p.args)
        lines.append(f"| {p.command} | {args} | {'yes' if p.ok else 'NO'} | {p.duration_s}s |")
    lines += ["", "## Findings", ""]
    lines += [f"- {e}" for e in plan.evidence] or ["- none"]
    lines += ["", "## Limitations and failed probes", ""]
    lines += [f"- {l}" for l in bundle.limitations] or ["- none recorded"]
    lines += [
        "",
        "## Plan",
        "",
        f"- primary flavor: {plan.primary_flavor}",
        f"- all flavors: {', '.join(plan.flavors)}",
        f"- backup-before-write: {'required' if plan.backup_required else 'not required'}",
        "",
        "## Risks",
        "",
    ]
    lines += [f"- {r}" for r in plan.risks] or ["- none identified"]
    lines += ["", "## Human todos before merge", ""]
    lines += [f"{i}. {t}" for i, t in enumerate(plan.human_todos, 1)] or ["1. none"]
