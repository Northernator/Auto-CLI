BACKEND_PY = Template('''"""Backend for $display_name harness.

Generated by auto-cli from REA evidence. Constants are baked in from
the recon pass - verify each one against the real application before merge.
"""

from __future__ import annotations

import json
import shutil
import sqlite3
import time
from pathlib import Path
from urllib.parse import urlsplit

TARGET_ROOT = Path($target_root_repr)
DEFAULT_DB = $default_db_repr
LOOPBACK_PORTS = $ports_repr
ENDPOINTS = $endpoints_repr
IPC_CHANNELS = $channels_repr
ALLOWED_ORIGINS = $origins_repr

_LOOPBACK_HOSTS = {"127.0.0.1", "localhost", "::1"}


class BackendError(Exception):
    """Raised for guard violations. CLI maps this to exit code 2."""


def resolve_db(override: str | None = None) -> Path:
    p = Path(override) if override else TARGET_ROOT / DEFAULT_DB
    if not p.exists():
        raise BackendError(f"database not found: {p}")
    return p


def db_info(path: Path) -> dict:
    """Read-only overview. Never opens for write."""
    uri = f"file:{path.as_posix()}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    try:
        tables = [
            r[0]
            for r in con.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
            ).fetchall()
        ]
        counts = {}
        for t in tables:
            counts[t] = con.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0]
        return {
            "path": str(path),
            "size_bytes": path.stat().st_size,
            "tables": tables,
            "row_counts": counts,
        }
    finally:
        con.close()


def db_schema(path: Path) -> dict:
    uri = f"file:{path.as_posix()}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    try:
        out = {}
        for (t,) in con.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
        ).fetchall():
            cols = con.execute(f'PRAGMA table_info("{t}")').fetchall()
            out[t] = [{"name": c[1], "type": c[2], "pk": bool(c[5])} for c in cols]
        return out
    finally:
        con.close()


def backup_db(path: Path, dest_dir: str | None = None) -> Path:
    """Timestamped copy before any write. Refuses to clobber an existing file."""
    stamp = time.strftime("%Y%m%d-%H%M%S")
    dest = Path(dest_dir) if dest_dir else path.parent
    dest.mkdir(parents=True, exist_ok=True)
    candidate = dest / f"{path.stem}.backup-{stamp}{path.suffix}"
    if candidate.exists():
        raise BackendError(f"backup target exists: {candidate}")
    shutil.copy2(path, candidate)
    return candidate


def run_query(path: Path, sql: str, limit: int = 100) -> dict:
    """Read-only SELECT only. Single statement. Row limit enforced."""
    stripped = sql.strip().rstrip(";").strip()
    head = stripped.lstrip("(").split(None, 1)[0].lower() if stripped else ""
    if head not in ("select", "with", "explain"):
        raise BackendError("only SELECT/WITH/EXPLAIN queries are allowed")
    if ";" in stripped:
        raise BackendError("multiple statements are not allowed")
    limit = max(1, min(int(limit), 10_000))
    uri = f"file:{path.as_posix()}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    try:
        cur = con.execute(stripped)
        rows = cur.fetchmany(limit + 1)
        truncated = len(rows) > limit
        rows = rows[:limit]
        cols = [d[0] for d in cur.description] if cur.description else []
        return {"columns": cols, "rows": [list(r) for r in rows], "truncated": truncated}
    except sqlite3.Error as e:
        raise BackendError(f"sqlite error: {e}") from e
    finally:
        con.close()


def export_table(path: Path, table: str, fmt: str, out: str) -> Path:
    schema = db_schema(path)
    if table not in schema:
        raise BackendError(f"unknown table: {table}")
    data = run_query(path, f'SELECT * FROM "{table}"', limit=1_000_000)
    dest = Path(out)
    if fmt == "json":
        dest.write_text(
            json.dumps([dict(zip(data["columns"], r)) for r in data["rows"]], indent=2),
            encoding="utf-8",
        )
    elif fmt == "csv":
        import csv

        with dest.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(data["columns"])
            w.writerows(data["rows"])
    else:
        raise BackendError(f"unknown format: {fmt}")
    return dest


def http_get(url: str, timeout: float = 10.0) -> dict:
    """Origin-scoped. Loopback is always allowed; remote hosts only if they
    were discovered during recon. An agent must not aim this at the internet."""
    parts = urlsplit(url)
    host = parts.hostname
    if host not in _LOOPBACK_HOSTS and parts.netloc not in ALLOWED_ORIGINS:
        raise BackendError(f"refusing URL outside discovered origins: {url}")
    import urllib.error
    import urllib.request

    try:
        with urllib.request.urlopen(url, timeout=timeout) as resp:
            body = resp.read(2_000_000).decode("utf-8", errors="replace")
            return {"status": resp.status, "url": url, "body": body}
    except urllib.error.HTTPError as e:
        body = e.read(2_000_000).decode("utf-8", errors="replace") if e.fp else ""
        return {"status": e.code, "url": url, "body": body}
''')

CLI_PY = Template('''"""cli-anything-$name - $display_name harness.

Generated by auto-cli. Every command supports --json (CLI-Anything
convention). Exit codes: 0 ok, 1 empty/not-found, 2 guard violation.
"""

from __future__ import annotations

import json
import sys

import click

from cli_anything.$module.core import backend


def _emit(ctx, payload: dict) -> None:
    if ctx.obj and ctx.obj.get("json"):
        click.echo(json.dumps(payload, indent=2, default=str))
    else:
        for k, v in payload.items():
            click.echo(f"{k}: {v}")


def _fail(msg: str) -> None:
    click.echo(f"error: {msg}", err=True)
    sys.exit(2)


@click.group()
@click.option("--json", "as_json", is_flag=True, help="machine-readable output")
@click.pass_context
def main(ctx: click.Context, as_json: bool) -> None:
    """$display_name - agent-native CLI (auto-cli generated)."""
    ctx.ensure_object(dict)
    ctx.obj["json"] = as_json


@main.command()
@click.argument("db", required=False)
@click.pass_context
def info(ctx: click.Context, db: str | None) -> None:
    """Read-only database overview."""
    try:
        _emit(ctx, backend.db_info(backend.resolve_db(db)))
    except backend.BackendError as e:
        _fail(str(e))


@main.command()
@click.argument("db", required=False)
@click.pass_context
def schema(ctx: click.Context, db: str | None) -> None:
    """Read-only table/column inventory."""
    try:
        _emit(ctx, backend.db_schema(backend.resolve_db(db)))
    except backend.BackendError as e:
        _fail(str(e))


@main.command()
@click.argument("db", required=False)
@click.option("--dest", default=None, help="backup directory (default: alongside the DB)")
@click.pass_context
def backup(ctx: click.Context, db: str | None, dest: str | None) -> None:
    """Timestamped copy of the database. Run before any write."""
    try:
        path = backend.resolve_db(db)
        out = backend.backup_db(path, dest)
        _emit(ctx, {"backup": str(out)})
    except backend.BackendError as e:
        _fail(str(e))


@main.command()
@click.argument("sql")
@click.argument("db", required=False)
@click.option("--limit", default=100, help="max rows (hard cap 10000)")
@click.pass_context
def query(ctx: click.Context, sql: str, db: str | None, limit: int) -> None:
    """Read-only SELECT with row limit."""
    try:
        _emit(ctx, backend.run_query(backend.resolve_db(db), sql, limit))
    except backend.BackendError as e:
        _fail(str(e))


@main.command("export")
@click.argument("table")
@click.argument("out")
@click.option("--format", "fmt", type=click.Choice(["csv", "json"]), default="json")
@click.argument("db", required=False)
@click.pass_context
def export_table(ctx: click.Context, table: str, out: str, fmt: str, db: str | None) -> None:
    """Export one table to CSV/JSON."""
    try:
        dest = backend.export_table(backend.resolve_db(db), table, fmt, out)
        _emit(ctx, {"exported": str(dest), "table": table, "format": fmt})
    except backend.BackendError as e:
        _fail(str(e))


@main.command()
@click.pass_context
def endpoints(ctx: click.Context) -> None:
    """List the loopback endpoints discovered by REA."""
    _emit(ctx, {"endpoints": backend.ENDPOINTS})


@main.command()
@click.argument("url")
@click.option("--timeout", default=10.0)
@click.pass_context
def get(ctx: click.Context, url: str, timeout: float) -> None:
    """GET one endpoint. Loopback always allowed; remote hosts only if
    discovered during recon (ALLOWED_ORIGINS in core/backend.py)."""
    try:
        _emit(ctx, backend.http_get(url, timeout))
    except backend.BackendError as e:
        _fail(str(e))


@main.command()
@click.pass_context
def channels(ctx: click.Context) -> None:
    """List IPC channels discovered by REA."""
    _emit(ctx, {"channels": backend.IPC_CHANNELS})


@main.command()
@click.argument("channel")
@click.option("--message", default="{}", help="JSON payload")
@click.pass_context
def send(ctx: click.Context, channel: str, message: str) -> None:
    """Send one IPC message. STUB: requires a live app session - wire the
    transport discovered in recon before enabling. Refuses by default."""
    if channel not in backend.IPC_CHANNELS:
        _fail(f"unknown channel: {channel}")
    _fail("send is not wired yet: recon found the channel, not the transport")


if __name__ == "__main__":
    main()
''')

