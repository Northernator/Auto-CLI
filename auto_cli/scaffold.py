def _category(plan: HarnessPlan) -> str:
    return {
        "local-server": "automation",
        "database": "media",
        "mcp-face": "automation",
        "scripting-runtime": "creative",
    }.get(plan.primary_flavor, "uncategorized")


def _forge_report(
    plan: HarnessPlan, bundle: EvidenceBundle, name: str, display_name: str, module: str
) -> str:
    lines = [
        f"# Forge report: {display_name}",
        "",
        "Generated by auto-cli. This document is the audit trail between",
        "REA evidence and the generated harness. Read it before opening a PR.",
        "",
        "## Target",
        "",
        f"`{plan.target}`",
        "",
        "## REA probes",
        "",
        "| command | args | ok | duration |",
        "| --- | --- | --- | --- |",
    ]
    for p in bundle.probes:
        args = " ".join(p.args)
        lines.append(f"| {p.command} | {args} | {'yes' if p.ok else 'NO'} | {p.duration_s}s |")
    lines += ["", "## Findings", ""]
    lines += [f"- {e}" for e in plan.evidence] or ["- none"]
    lines += ["", "## Limitations and failed probes", ""]
    lines += [f"- {l}" for l in bundle.limitations] or ["- none recorded"]
    lines += [
        "",
        "## Plan",
        "",
        f"- primary flavor: {plan.primary_flavor}",
        f"- all flavors: {', '.join(plan.flavors)}",
        f"- backup-before-write: {'required' if plan.backup_required else 'not required'}",
        "",
        "## Risks",
        "",
    ]
    lines += [f"- {r}" for r in plan.risks] or ["- none identified"]
    lines += ["", "## Human todos before merge", ""]
    lines += [f"{i}. {t}" for i, t in enumerate(plan.human_todos, 1)] or ["1. none"]
    lines += [
        "",
        "## Verification scope",
        "",
        "- Scaffolding records reconnaissance findings; it does not itself run live checks.",
        "- See VERIFICATION.md for any subsequent HTTP/database checks and GUI-REPORT.md for GUI discovery.",
        "- Generated unit tests use fixtures; they do not establish success on real application workflows.",
        "- Workflow commands require a separate real application acceptance test.",
        "",
    ]
    return "\n".join(lines)
