TEST_CORE_PY = Template('''"""Unit tests for the $module backend. No real app required."""

import sqlite3
from pathlib import Path

import pytest

from cli_anything.$module.core import backend


@pytest.fixture()
def db(tmp_path: Path) -> Path:
    p = tmp_path / "fixture.db"
    con = sqlite3.connect(p)
    con.executescript(
        "CREATE TABLE tracks (id INTEGER PRIMARY KEY, title TEXT);"
        "INSERT INTO tracks (title) VALUES ('a'), ('b');"
    )
    con.commit()
    con.close()
    return p


def test_db_info_is_read_only(db):
    info = backend.db_info(db)
    assert info["tables"] == ["tracks"]
    assert info["row_counts"]["tracks"] == 2


def test_schema_lists_columns(db):
    schema = backend.db_schema(db)
    assert [c["name"] for c in schema["tracks"]] == ["id", "title"]
    assert schema["tracks"][0]["pk"] is True


def test_backup_creates_timestamped_copy(db):
    out = backend.backup_db(db)
    assert out.exists() and out != db
    assert db.exists()


def test_backup_refuses_clobber(db):
    first = backend.backup_db(db)
    with pytest.raises(backend.BackendError):
        backend.backup_db(db, dest_dir=str(first.parent))


def test_query_allows_select_only(db):
    with pytest.raises(backend.BackendError):
        backend.run_query(db, "DELETE FROM tracks")
    with pytest.raises(backend.BackendError):
        backend.run_query(db, "SELECT 1; DROP TABLE tracks")


def test_query_row_limit(db):
    res = backend.run_query(db, "SELECT * FROM tracks", limit=1)
    assert len(res["rows"]) == 1
    assert res["truncated"] is True


def test_export_json(db, tmp_path):
    out = tmp_path / "tracks.json"
    backend.export_table(db, "tracks", "json", str(out))
    import json

    data = json.loads(out.read_text())
    assert data == [{"id": 1, "title": "a"}, {"id": 2, "title": "b"}]


def test_http_get_refuses_remote():
    with pytest.raises(backend.BackendError):
        backend.http_get("https://example.com/x")
''')

