"""Live verification: prove recon findings against the running target.

REA's static evidence says an endpoint exists; this module asks the endpoint.
Verification states:
  verified   - the finding behaved exactly as recon predicted
  corrected  - recon was close but wrong; the verified value replaces it
  failed     - recon predicted it, reality disagrees (app not running, moved)
  unverifiable- static-only finding (IPC channels, encrypted DBs)

The output is a VERIFICATION.md an agent (or human) can finish from: every
corrected constant is patched into the generated backend automatically.
"""

from __future__ import annotations

import json
import re
import sqlite3
import urllib.error
import urllib.request
from dataclasses import dataclass, field, asdict
from pathlib import Path

from .evidence import EvidenceBundle
from .surface import HarnessPlan

LOOPBACK_HOSTS = {"127.0.0.1", "localhost", "::1"}


@dataclass
class Verification:
    kind: str
    target: str
    state: str  # verified | corrected | failed | unverifiable
    detail: str = ""
    verified_value: str = ""

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class VerificationReport:
    target: str
    checks: list[Verification] = field(default_factory=list)
    patches: dict = field(default_factory=dict)

    @property
    def counts(self) -> dict[str, int]:
        out: dict[str, int] = {}
        for c in self.checks:
            out[c.state] = out.get(c.state, 0) + 1
        return out

    def to_dict(self) -> dict:
        return {
            "target": self.target,
            "counts": self.counts,
            "checks": [c.to_dict() for c in self.checks],
            "patches": self.patches,
        }

    def markdown(self) -> str:
        lines = [
            f"# Verification report: {self.target}",
            "",
            "Generated by `auto-cli verify`. Each recon finding was tested",
            "against the live target where possible.",
            "",
            "| finding | state | detail |",
            "| --- | --- | --- |",
        ]
        for c in self.checks:
            lines.append(f"| {c.kind}: {c.target[:60]} | {c.state} | {c.detail[:80]} |")
        lines += ["", "## Summary", ""]
        for state, n in sorted(self.counts.items()):
            lines.append(f"- {state}: {n}")
        if self.patches:
            lines += ["", "## Constants patched into the generated backend", ""]
            for k, v in self.patches.items():
                lines.append(f"- `{k}` = `{v}`")
        lines.append("")
        return "\n".join(lines)


def _get(url: str, timeout: float) -> tuple[int, str, str]:
    req = urllib.request.Request(url, headers={"User-Agent": "auto-cli-verify"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, resp.headers.get("Content-Type", ""), resp.read(2_000_000).decode(
                "utf-8", errors="replace"
            )
    except urllib.error.HTTPError as e:
        return e.code, e.headers.get("Content-Type", "") if e.headers else "", ""
    except (urllib.error.URLError, OSError) as e:
        return -1, "", str(e)


def _json_shape(body: str) -> str:
    try:
        doc = json.loads(body)
    except json.JSONDecodeError:
        return "non-JSON body"
    if isinstance(doc, dict):
        keys = list(doc.keys())
        inner = ""
        for v in doc.values():
            if isinstance(v, list) and v and isinstance(v[0], dict):
                inner = f"[] of objects with keys {list(v[0].keys())}"
                break
        return f"object keys={keys}" + (f", {inner}" if inner else "")
    if isinstance(doc, list):
        if doc and isinstance(doc[0], dict):
            return f"array of {len(doc)} objects, keys={list(doc[0].keys())}"
        return f"array of {len(doc)} scalars"
    return type(doc).__name__


def verify(
    bundle: EvidenceBundle,
    plan: HarnessPlan,
    scaffold_dir: str | Path,
    timeout: float = 5.0,
) -> VerificationReport:
    report = VerificationReport(target=plan.target)
    root = Path(scaffold_dir)
    backend_file = next(root.glob("cli_anything/*/core/backend.py"), None)
    backend_src = backend_file.read_text(encoding="utf-8") if backend_file else ""
    verified_endpoints: list[str] = []

    # 1. Loopback endpoints: ask them.
    for f in bundle.of_kind("endpoint"):
        url = f.value
        if not url.startswith(("http://", "https://")):
            if "127.0.0.1" in url or "localhost" in url:
                url = "http://" + url.lstrip("/")
            else:
                report.checks.append(
                    Verification(
                        kind="endpoint",
                        target=f.value,
                        state="unverifiable",
                        detail="static expression, not a URL - resolve manually",
                    )
                )
                continue
        status, ctype, body = _get(url, timeout)
        if status == 200:
            shape = _json_shape(body)
            report.checks.append(
                Verification(
                    kind="endpoint",
                    target=url,
                    state="verified",
                    detail=f"200 {ctype}, {shape}",
                    verified_value=url,
                )
            )
            verified_endpoints.append(url)
        elif status in (502, 503, 504):
            # Proxied environments answer everything; a 502 on loopback is
            # far more likely a proxy than the app itself.
            report.checks.append(
                Verification(
                    kind="endpoint",
                    target=url,
                    state="failed",
                    detail=f"HTTP {status} - proxy or dead app; retry with proxies disabled",
                )
            )
        elif status > 0:
            report.checks.append(
                Verification(kind="endpoint", target=url, state="failed", detail=f"HTTP {status}")
            )
        else:
            report.checks.append(
                Verification(
                    kind="endpoint",
                    target=url,
                    state="failed",
                    detail=f"no response ({body[:60]}) - is the app running?",
                )
            )

    # 2. Database: resolve, read schema, compare with baked constants.
    dbs = bundle.of_kind("database")
    if dbs:
        rel = dbs[0].value
        target = Path(plan.target)
        base = target.parent if target.is_file() else target
        db = Path(rel)
        candidates = [db] if db.is_absolute() else [base / db, db]
        db_path = next((p for p in candidates if p.exists()), None)
        if db_path is None:
            report.checks.append(
                Verification(kind="database", target=rel, state="failed", detail="file not found at recon path")
            )
        else:
            try:
                con = sqlite3.connect(db_path.resolve().as_uri() + "?mode=ro", uri=True)
                tables = [
                    r[0]
                    for r in con.execute(
                        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
                    )
                ]
                con.close()
                baked = re.findall(r'DEFAULT_DB = "([^"]*)"', backend_src)
                if baked and baked[0] != rel:
                    report.patches["DEFAULT_DB"] = rel
                target_root = Path(plan.target).resolve()
                report.patches["TARGET_ROOT"] = str(target_root.parent if target_root.is_file() else target_root)
                report.checks.append(
                    Verification(
                        kind="database",
                        target=str(db_path),
                        state="verified",
                        detail=f"readable, tables={tables}",
                        verified_value=str(db_path),
                    )
                )
            except sqlite3.Error as e:
                report.checks.append(
                    Verification(kind="database", target=str(db_path), state="failed", detail=str(e))
                )

    # 3. IPC channels: static only. Honest about it.
    for f in bundle.of_kind("ipc_channel"):
        report.checks.append(
            Verification(
                kind="ipc_channel",
                target=f.value,
                state="unverifiable",
                detail="static observation - needs the app running with a live session",
            )
        )

    # 4. Patch verified endpoint list into the backend.
    if backend_file and verified_endpoints:
        import ast

        src = backend_file.read_text(encoding="utf-8")
        existing = re.search(r"ENDPOINTS = (\[[^\]]*\])", src)
        if existing:
            try:
                current = ast.literal_eval(existing.group(1))
            except (ValueError, SyntaxError):
                current = []
            merged = sorted(set(verified_endpoints) | set(current))
            src = src.replace(existing.group(0), f"ENDPOINTS = {merged!r}")
            backend_file.write_text(src, encoding="utf-8")
            report.patches["ENDPOINTS"] = merged

    return report


def write_report(report: VerificationReport, scaffold_dir: str | Path) -> Path:
    root = Path(scaffold_dir)
    # accept either the agent-harness dir or its parent
    if root.name != "agent-harness":
        found = next(root.rglob("agent-harness"), None)
        if found:
            root = found
    p = root / "VERIFICATION.md"
    p.write_text(report.markdown(), encoding="utf-8")
    (root / "verification.json").write_text(json.dumps(report.to_dict(), indent=2), encoding="utf-8")
    return p
